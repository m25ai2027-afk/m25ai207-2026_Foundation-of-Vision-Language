# 1. Define corpus sentences
corpus_sentences = [
    "Hello world This is a simple sentence",
    "Tokenization splits text into individual words",
    "Lets clean and tokenize these sentences",
    "new york time angeles",
    "loss angeles times"
]

# 2. Tokenize and build vocabulary
def build_vocab(sentences):
    words = []
    for sentence in sentences:
        cleaned = re.sub(r'[^\w\s]', '', sentence.lower())
        words.extend(cleaned.split())

    unique_words = sorted(list(set(words)))
    word_to_id = {word: idx for idx, word in enumerate(unique_words)}
    id_to_word = {idx: word for word, idx in word_to_id.items()}
    return words, unique_words, word_to_id, id_to_word

tokens, vocab, word_to_id, id_to_word = build_vocab(corpus_sentences)
print(f"Vocabulary Size: {len(vocab)}")
print("Word to ID:", list(word_to_id.items())[:5])
print("ID to Word:", list(id_to_word.items())[:5])

# 3. Create Training Pairs (Skip-gram model: target word -> context words)
def generate_training_pairs(sentences, word_to_id, window_size=2):
    training_pairs = []
    for sentence in sentences:
        cleaned = re.sub(r'[^\w\s]', '', sentence.lower())
        words = cleaned.split()
        indices = [word_to_id[w] for w in words if w in word_to_id]

        for i, center_word_id in enumerate(indices):
            # Define boundaries for the window
            start = max(0, i - window_size)
            end = min(len(indices), i + window_size + 1)

            for j in range(start, end):
                if i != j:
                    context_word_id = indices[j]
                    training_pairs.append((center_word_id, context_word_id))
    return np.array(training_pairs)

training_pairs = generate_training_pairs(corpus_sentences, word_to_id, window_size=1)
print(f"Generated {len(training_pairs)} training pairs.")
print("First 10 pairs (Center ID, Context ID):")
for center, context in training_pairs[:10]:
    print(f"  {id_to_word[center]} ({center}) -> {id_to_word[context]} ({context})")

# 1. Initialize Word2Vec Hyperparameters and Weights
np.random.seed(42)

embedding_dim = 10
vocab_size = len(vocab)
learning_rate = 0.05
epochs = 500

# W1: Word embeddings matrix (V x N)
W1 = np.random.randn(vocab_size, embedding_dim) * 0.1
# W2: Context word weights matrix (N x V)
W2 = np.random.randn(embedding_dim, vocab_size) * 0.1

print(f"Embedding matrix W1 shape: {W1.shape}")
print(f"Context matrix W2 shape: {W2.shape}")

# Helper Softmax function
def softmax(x):
    e_x = np.exp(x - np.max(x))
    return e_x / e_x.sum(axis=0)

# 2. Training loop
loss_history = []

for epoch in range(epochs):
    epoch_loss = 0
    for target_id, context_id in training_pairs:
        # Forward Pass:
        # Step A: Get embedding vector for target word (1 x N)
        h = W1[target_id]

        # Step B: Score output for all words in vocabulary (V x 1)
        u = np.dot(W2.T, h)

        # Step C: Convert scores to probabilities using softmax
        y_pred = softmax(u)

        # Compute cross-entropy loss for this sample
        epoch_loss += -np.log(y_pred[context_id] + 1e-15)

        # Backward Pass (Gradients):
        # dL/du = y_pred - y_true (where y_true is 1 at context_id, else 0)
        e = y_pred.copy()
        e[context_id] -= 1.0

        # Gradients for W2 and W1
        dW2 = np.outer(h, e)
        dW1_target = np.dot(W2, e)

        # Gradient Descent update
        W2 -= learning_rate * dW2
        W1[target_id] -= learning_rate * dW1_target

    loss_history.append(epoch_loss / len(training_pairs))
    if (epoch + 1) % 100 == 0 or epoch == 0:
        print(f"Epoch {epoch+1}/{epochs} | Average Loss: {loss_history[-1]:.4f}")

# Plot the training loss curve
from matplotlib import pyplot as plt

plt.figure(figsize=(8, 5))
plt.plot(loss_history, label='Skip-gram Loss')
plt.title('Word2Vec Training Loss')
plt.xlabel('Epochs')
plt.ylabel('Loss')
plt.grid(True)
plt.legend()
plt.show()